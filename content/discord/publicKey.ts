// ───────────────────────────────────────────────────────────────
// Discord アプリの Public Key（署名の検証鍵）。
//
// 【なぜリポジトリに置いてよいか・2026-08-10】
// これは秘密情報ではない。Discord が配る Public Key は、Discord から届いた
// リクエストの署名を**検証する**ための公開鍵であって、署名を**作る**ことはできない
// （署名できるのは対になる秘密鍵を持つ Discord 側だけ）。Discord 自身も開発者ポータルの
// General Information に平文で表示している。したがって、これが漏れても誰も
// 「Discord からのリクエストになりすます」ことはできない。
//
// ANNICT_TOKEN のような**秘密**とは性質が違うので、CLAUDE.md の
// 「トークンはサーバー側だけで使う／コミットしない」の対象ではない。
// （なお、この値を読むのは app/api/discord/route.ts＝サーバー側だけである点も同じ。）
//
// 【なぜ環境変数ではなくここに置くか】
// Vercel の環境変数に入れるには Vercel ダッシュボードへのログインが要る。
// ログインできない状況でも、main への push（＝Vercelの自動デプロイ）だけで
// 設定を反映できるようにするため、コード側に置ける道を用意した。
//
// 環境変数 `DISCORD_PUBLIC_KEY` があれば**そちらが優先される**ので、
// 後から環境変数に移すこともできる（その場合ここは空に戻してよい）。
//
// 【値の形式】Discord の Public Key は 0-9 と a-f だけの64文字。
// 空文字のままなら Discord 連携は無効（/api/discord は 503 を返すだけで、
// サイトの他の機能には一切影響しない）。
// 形式が不正なまま気づかない事故を防ぐため、`node scripts/check.ts` が
// 「空、または16進64文字」であることを検査している。
//
// 【鍵を変えるとき】Discord でアプリを作り直した場合はここを差し替えて main に push する。
// ───────────────────────────────────────────────────────────────
export const DISCORD_PUBLIC_KEY_FALLBACK = "";
