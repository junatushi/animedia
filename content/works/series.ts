//
// サービス名が付くと60位→10位に跳ね上がる。つまり作品ページの中身（配信サービス名）は
// 効いていて、足りないのは**ページの評価そのもの**。そして1期（/anime/10591、2024夏）は
// **表示回数ゼロ**＝検索に存在しないのと同じで、しかも1期と2期は互いにリンクが無かった。
// 同じ作品名で検索需要を分け合う2ページが、内部リンクで繋がっていない状態だった。
//
// 【なぜAnnictのseriesListを使わないか】
// Annictにはシリーズを表す `seriesList` があるが、この作業環境からは
// トークンもAnnictへの通信も無く**実際の応答を確かめられない**。未検証のフィールドを
// シーズン一覧のGraphQLに足すと、フィールド名や形が違ったときにクエリ全体が
// エラーになり、**サイト全部のデータ取得が壊れる**（配信情報が全作品で消える）。
// 得られるのは内部リンク、失うのはサイトの根幹なので、交換として釣り合わない。
// content/works/extraServices.ts・releaseDates.ts と同じ人力補完の方式にする。
//
// 【方針】CLAUDE.mdの補完データと同じ。
//   ・公式サイト等の一次情報で確認できたものだけ書く（推測でシリーズを繋がない）
//   ・`sourceUrl`（出典）と `confirmedDate`（確認日）を必ず入れる
//   ・全作品は追わない。**実測で需要が確認できた作品から都度追加する**
//     （GSCで表示回数が立っている作品が対象。`content/works/*.json` の faq と同じ考え方）
//   ・作品名から「◯期」を機械的に推測して繋ぐことは**しない**。
//     同名の別作品・スピンオフ・総集編を誤って繋ぐと、利用者を関係の無いページへ送る
//
// 【表示】作品ページ（app/anime/[id]/page.tsx）の「シリーズの他の作品」欄。
// 放送が終わったシリーズ作品に「いま配信中」とは書かない（CLAUDE.mdの基本ルール）。
// ここは作品ページへのリンクと放送クールを出すだけで、配信の可否には触れない。

export interface SeriesWork {
  /** Annict の作品ID（/anime/{id} と同じ） */
  id: number;
  /** 表示名。作品名そのままではなく「第1期」「劇場版」など、シリーズ内での位置が分かる短い名前 */
  label: string;
}

export interface SeriesEntry {
  /** シリーズの表示名（見出しに使う） */
  title: string;
  /** 放送順。2件以上必要（1件ではシリーズにならない） */
  works: SeriesWork[];
  /** 一次情報のURL（公式サイト等） */
  sourceUrl: string;
  /** 出典を確認した日（YYYY-MM-DD） */
  confirmedDate: string;
}

