// 声優個人ページ（app/person/[name]/[year]/[season]/page.tsx）と、そこへリンクする側
// （app/anime/[id]/page.tsx の声優名リンク）の両方が参照する共有定数。
// 「今期2作品以上に出演」の声優だけをページ化する閾値（components/SeasonExplorer.tsx の
// 声優チップと同じ基準）。作品個別ページの声優名は、この閾値を満たさない相手にリンクを
// 張ると404になってしまうため、リンクを出す前に必ずこの値でフィルタする。
import { currentYearSeason } from "@/lib/resolveSeasonParams";

export const PERSON_PAGE_MIN_APPEARANCES = 2;

// ───────────────────────────────────────────────────────────────
// 過去年の「無名の声優」のページだけを検索索引から外す（2026-08-25判断 → 2026-08-31修正）
//
// 【最初の版が間違っていた点】2026-08-25に「今期のクール以外は全部noindex」を書いた。
// 根拠は「悪化6.86位のうち4.77（70%）が過去クールの声優ページ由来で、除いてもクリックは
// 減らない」という計算だったが、これは**途中までしか埋まっていない週**（作品ページの表示が
// まだ966件だった時点）のデータで出した数字で、誤りだった。完全な週で計算し直すと:
//   ・08-17週（完全）: 作品 2,881表示@22.09位 / 声優 363表示@38.24位 / 全体 3,401表示@23.65位
//   ・声優ページは表示の **10.7%** にすぎず、全部除いても 23.65 → 21.91位（改善1.74＝30%）
//   ・悪化の残り70%は作品ページの表示が137→2,881件（21倍）に増えたことによる。
//     ただし作品ページは順位を落としておらず（21.70→22.09→23.21位）、クリックの主収入源
//     （週34クリック）なので、これは直すべき問題ではない。
// さらに「クリックは減らない」も誤りだった。28日のページ別実測で、過去年の声優ページは
// 37表示・**6クリック**・平均20.84位を取っている:
//   前野智昭/2017/winter 4.0位 / 斉藤壮馬/2024/summer 8.0位 / 森川智之/2019/spring 69.2位 /
//   櫻井孝宏/2023/summer 43.5位 / 宮野真守/2026/winter 6.6位 / 谷山紀章/2026/winter 1.0位
// 「今期のクールだけ」という粒度も粗すぎた。2026/winter のページ（6.6位・1.0位でクリック
// あり）まで巻き添えで外れる。実際の検索語は「宮野真守 2026 アニメ」のように**年**の粒度で、
// クールの粒度ではない。
//
// 【いまの規則】
//   ①今年のクールは全部索引に載せる（2026/winter・spring・summer・autumn すべて）。
//   ②過去年は「出演作の多い声優」だけ載せる。上のクリックを取っている過去年の4人は
//     総出演 83 / 98 / 70 / 97 作品で、閾値50なら全員が残る（余裕を持たせてある）。
//     索引の総出演数は content/archive/people.json（スナップショット由来）で数える。
// これで過去年の声優ページは 4,483 → 約2,374件になり、**実測でクリックを取っている
// ページは1件も落ちない**。
//
// 【外し方】ページ自体は消さない（404にしない）。noindex にして sitemap から降ろすだけ。
//   ・過去クールの作品ページ（sitemapに載せている1,961件）への内部リンクを残したい。
//   ・可逆にしておきたい（効果は weeklyByType で後から判定する）。
//
// 【やってはいけないこと】「薄いページ＝Googleのポリシー違反だから消す」という理屈で
// 広げないこと。scaled content abuse の定義は「順位操作が主目的」かつ「利用者の役に
// 立たない」の両方が要件で、このサイトの声優ページはどちらも満たさない。これは
// **薄い面を検索の入口に使わないという運用判断**であって、違反の回避ではない。
// 経緯は docs/operations.md の㉜、実測は docs/seo-2026-08-25/。
export const PERSON_PAGE_INDEX_MIN_TOTAL_WORKS = 50;

// 声優のクール別ページを検索索引に載せてよいか。
// totalWorks は content/archive/people.json に載っているその人の総出演数
// （索引に無い人は0を渡す。今年のクールなら0でも索引に載る＝①の規則が先に効く）。
export function shouldIndexPersonSeasonPage(
  year: string | number,
  totalWorks: number
): boolean {
  const cur = currentYearSeason();
  if (Number(year) >= Number(cur.year)) return true;
  return totalWorks >= PERSON_PAGE_INDEX_MIN_TOTAL_WORKS;
}
