// 声優個人ページ（app/person/[name]/[year]/[season]/page.tsx）と、そこへリンクする側
// （app/anime/[id]/page.tsx の声優名リンク）の両方が参照する共有定数。
// 「今期2作品以上に出演」の声優だけをページ化する閾値（components/SeasonExplorer.tsx の
// 声優チップと同じ基準）。作品個別ページの声優名は、この閾値を満たさない相手にリンクを
// 張ると404になってしまうため、リンクを出す前に必ずこの値でフィルタする。
import { currentYearSeason } from "@/lib/resolveSeasonParams";

export const PERSON_PAGE_MIN_APPEARANCES = 2;

// ───────────────────────────────────────────────────────────────
// 過去クールの声優ページを検索索引から外す（2026-08-25導入）
//
// 【なぜ外すか（実測。docs/seo-2026-08-25/facts.md）】
// 2026-08-11に過去クールの声優ページ4,483件をsitemapへ追加した。判断の根拠は
// 「声優ページは全ページ種別の中で突出して強い（5.9位・CTR9.5%）」という実測だったが、
// **その実測はすべて“今期の”声優ページのもの**で、過去クールぶんには当てはまらなかった。
//
// 索引到達後（2026-08-19〜20）のGSC実測:
//   ・声優ページ全体の平均掲載順位が 5.9位 → 47.0位 に崩壊した。
//   ・上位100に残る声優ページは今も 6.73位（表示115・クリック11）で、その3件は
//     すべて今期（2026/summer）。過去クールぶんは1件（櫻井孝宏/2023/summer）だけが
//     34.3位で顔を出し、残り約76表示は逆算で平均108位付近にいた。
//   ・サイト全体の週次平均は 17.88位 → 24.74位。悪化 6.86 のうち **4.77（70%）が
//     この新規の薄い声優ページ由来**。それでいて表示回数の比率は12.2%、
//     クリックへの寄与は1件。除くと週次平均は 19.94位 に戻り、クリックは減らない。
//
// 【構造的な理由】検索されるのは「悠木碧 2026」のような“今期＋人名”か、
// 「櫻井孝宏 出演作」のような“通期”であって、「櫻井孝宏 2023年夏」ではない。
// 過半数（2,516/4,483＝56.1%）が「そのクールに2作品出ているだけ」のページで、
// クールで割ること自体がこの面の検索意図と噛み合っていない。
//
// 【もう一つの理由】Googleは 2026-08-18〜08-21 に August 2026 spam update を展開し、
// scaled content abuse（機械的に量産された薄いページ）を名指ししている。
// 急増の時期と重なっており、手元のデータでは索引到達との切り分けができない
// （docs/seo-2026-08-25/facts.md の11節）。どちらが原因でも打ち手は同じ方向。
//
// 【外し方】ページ自体は消さない（404にしない）。noindex にして sitemap から降ろすだけ。
//   ・過去クールの作品ページ（sitemapに載せている1,961件）への内部リンクは残したい。
//   ・「配信情報がある作品」の横断導線として人には価値があり、壊す理由が無い。
//   ・可逆にしておきたい（効果はweeklyByTypeで後から判定する）。
// 今期の声優ページは**触らない**。サイト最大の資産（/person/悠木碧/2026/summer は
// 5.8位・9クリック）がそこにあり、実測で唯一うまくいっている面だから。
export function isCurrentSeasonPersonPage(year: string | number, season: string): boolean {
  const cur = currentYearSeason();
  return String(year) === cur.year && season === cur.season;
}

// 声優のクール別ページを検索索引に載せてよいか。今期だけ true。
export function shouldIndexPersonSeasonPage(year: string | number, season: string): boolean {
  return isCurrentSeasonPersonPage(year, season);
}
