// 事前生成（generateStaticParams）に載せてよいパラメータの判定。
//
// ───────────────────────────────────────────────────────────────
// 【なぜこのファイルがあるか・2026-08-31の本番障害】
//
// 本番で **日本語名の事前生成ページが全て404** になっていた。実測:
//
//   /person/悠木碧/2026/summer  （今年＝動的）      → 200
//   /person/悠木碧/2024/summer  （過去年＝事前生成） → 404
//   /studio/CloverWorks         （ASCII＝事前生成）  → 200
//   /studio/ぴえろ              （日本語＝事前生成） → 404
//
// 無作為抽出で **日本語名 13/13 が404・ASCII名 5/5 が200**。
// sitemapに載せていて404だったページは約2,826件:
//   過去年の声優ページ 2,351 ／ 監督 376 ／ 制作会社 99
//
// **手元では絶対に気づけない**。同じコードをローカルで `next start` すると全て200を返し、
// `.next/prerender-manifest.json` のキーも成果物のファイル名も正しく
// パーセントエンコードされている（`/studio/%E3%81%8E%E3%82%83%E3%82%8D%E3%81%A3%E3%81%B7`）。
// 本番の `X-Matched-Path` もそのキーと一致しているのに404になる。
// docs/operations.md の⑦-10（ソースは正しいのに本番HTMLだけが空）と同じ型の壊れ方。
//
// 【推測している原因（未確定）】
// 3ページとも `generateStaticParams` は **すでに `encodeURIComponent(name)` を返している**
// （studio/director は2026-08-12から、person は2026-08-25から）。そのため成果物は
// `%E3%81%B4%E3%81%88%E3%82%8D.html` という名前で焼かれる。もしVercelが静的ファイルを
// 探す前にリクエストパスをデコードしているなら、`ぴえろ.html` を探して見つからない。
// ASCII名だけ動くのは、エンコードとデコードが恒等写像になるから。
// **この仮説は未検証**。検証はVercelのビルドログと、下のカナリア（PREGEN_CANARY）で行う。
//
// 【いまの応急処置】
// 非ASCIIのパラメータは事前生成に載せない＝オンデマンドISRに任せる。動的に描画される
// ページは日本語名でも200を返すことが本番で実測できている（上の対照実験）。
//
// 【代償】docs/operations.md の㉝（Vercel利用上限超過でサイトが停止した件）で、
// 事前生成はISR Writesを1件も消費しない＝書き込みの下限を決めていると分かっている。
// 非ASCIIを外すとその下限が戻る。**これは応急処置であって恒久対応ではない。**
// 原因が判明したら、この関数ごと消して全件を事前生成に戻すこと。
// ───────────────────────────────────────────────────────────────

/**
 * 事前生成に載せてよい名前か。
 *
 * 【判定の根拠・2026-08-31の本番実測】
 * 決め手は「日本語かどうか」ではなく **パーセントエンコードが要るかどうか** だった:
 *
 *   /studio/CloverWorks      （エンコード不要） → 200
 *   /studio/A-1%20Pictures   （空白→%20）      → 404  ← ASCII名でも404
 *   /studio/ぴえろ           （日本語）        → 404
 *
 * `generateStaticParams` が `encodeURIComponent(name)` を返しているため、成果物は
 * `A-1%20Pictures.html` というファイル名で焼かれる。Vercelは静的ファイルを探す前に
 * リクエストパスをデコードしていると見られ、`A-1 Pictures.html` を探して見つからない。
 * エンコードが恒等写像になる名前（英数字だけ）はたまたま一致するので動く。
 *
 * したがって門番の条件は「エンコードしても文字列が変わらないこと」。
 * これを外すと `A-1 Pictures` のような**ASCIIなのに404**の取りこぼしが出る。
 * 恒久対応ではないので、原因が確定して直したらこの関数ごと消す。
 */
export function canPrerenderParam(name: string): boolean {
  return encodeURIComponent(name) === name;
}
/**
 * 原因究明のためのカナリア（2026-08-31追加）。
 *
 * 上の推測（「Vercelはデコード後のパスで静的ファイルを探しているのでは」）を確かめるため、
 * **ここに挙げた名前だけは非ASCIIでも事前生成に載せる。ただしエンコードせず生のまま渡す。**
 * 次の本番デプロイのあと、この3件が200なら仮説が当たり＝
 * `encodeURIComponent` をやめれば全件を事前生成に戻せる。404のままなら仮説は外れ。
 *
 * 3件に絞ってあるのは、外れたときの被害を「いまも404の3ページ」に限るため
 * （どちらに転んでも現状より悪くならない）。
 * 判定がついたらこの配列ごと消すこと。
 */
export const PREGEN_CANARY_STUDIOS = ["ぴえろ", "シャフト", "京都アニメーション"];
