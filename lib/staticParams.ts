// 動的セグメント（[name]）を事前生成するときの、パラメータの渡し方と読み方。
//
// ───────────────────────────────────────────────────────────────
// 【なぜこのファイルがあるか・2026-08-31の本番障害】
//
// 本番で **事前生成した制作会社・監督・声優（過去年）のページが404** を返していた。
// sitemapに載せていて404だったのは約2,826ページ（声優2,351／監督376／制作会社99）。
//
// 決め手は「日本語かどうか」ではなく **パーセントエンコードが要るかどうか** だった:
//
//   /studio/CloverWorks        （エンコード不要） → 200
//   /studio/A-1%20Pictures     （空白→%20）      → 404  ← ASCII名でも404
//   /studio/ぴえろ             （日本語）        → 404
//   /person/悠木碧/2026/summer （今年＝動的）     → 200  ← 同じ名前でも動的なら通る
//
// 【原因（2026-08-31にカナリアで確定）】
// 3ページとも `generateStaticParams` が `encodeURIComponent(name)` を返していた。
// そのため成果物が `ぴえろ.html` ではなく `%E3%81%B4%E3%81%88%E3%82%8D.html` という
// ファイル名で焼かれる。**Vercelはリクエストパスをデコードしてから静的ファイルを探す**ため、
// `ぴえろ.html` を探して見つからない。エンコードが恒等写像になる名前（英数字のみ）だけが
// たまたま一致して動いていた。
//
// 確定のさせ方: 3件だけ「エンコードせず生の名前で」事前生成するカナリアを本番に出し、
// 200を確認した（/studio/ぴえろ・シャフト・京都アニメーション がいずれも200）。
// 同時に、応急処置として動的に回した約2,826ページも200に戻った（抜き取り19/19）。
//
// 【したがっての規則】
//   **`generateStaticParams` にはエンコードせず生の名前を渡す。**
//   route key を作るときに Next.js が自分でエンコードするので、こちらで二重にやらない。
//   `node scripts/check.ts` の「事前生成に名前をエンコードして渡さない」節が逆戻りを見張る。
//
// 【なぜ手元では気づけなかったか】
// 同じコードをローカルで `next start` すると全て200を返し、
// `.next/prerender-manifest.json` のキーも成果物のファイル名も正しくエンコードされており、
// 本番の `X-Matched-Path` もそのキーと一致していた。ソース・ビルド成果物・ルーティングの
// どれを見ても正しく、**本番に実際のリクエストを投げる以外に検知手段が無い**
// （docs/operations.md の⑦-10と同じ型）。再発検知は
// `scripts/verify-production.sh` のG節（sitemapのURLが200を返すか。日本語名を優先して選ぶ）。
//
// 経緯は docs/operations.md の㊱。
// ───────────────────────────────────────────────────────────────

/**
 * 動的セグメントの `params.name` から、表示・検索に使う名前を復元する。
 *
 * 渡ってくる形が経路によって違う:
 *   ・事前生成（generateStaticParams が返した値）… **生の名前**（"ぴえろ"）
 *   ・オンデマンド（実リクエスト）              … **エンコード済み**（"%E3%81%B4…"）
 * どちらも decodeURIComponent で正しい名前になる（生の名前は素通りする）。
 *
 * ただし `decodeURIComponent` は不正な `%` を含む文字列で URIError を投げる。名前は
 * 外部データ（Annict由来の索引）なので、将来 `%` を含む名前が現れると**ビルドごと落ちる**。
 * そうなるより、元の文字列を返して1ページだけ表示が崩れるほうが被害が小さいので握る。
 * （2026-08-31時点の実データ2,074名には `%` を含む名前も、復元に失敗する名前も無い。）
 */
export function decodeParamName(raw: string): string {
  try {
    return decodeURIComponent(raw);
  } catch {
    return raw;
  }
}
