// Xを「開いて操作する」までの手数を減らすためのURL組み立て（2026-08-06導入）。
//
// 【なぜ要るのか】Xへの投稿・リプ・フォローは手動運用（X APIが2026年2月に有料化された
// ため。CLAUDE.md参照）で、週次X成長キット（x-growth.yml）と日次ダイジェストが
// GitHub Issueに下書きを起票する仕組みになっている。
// ところが 2026-08-06 時点でIssueの消化状況を見ると:
//   ・日次の「Xへの投稿下書き」は 7/20〜7/30 は毎日closeされていたのに、7/31以降は
//     7件が連続でopenのまま（#27・#28・#29・#31・#32・#33・#37）。
//   ・**週次X成長キット（#22・#30）は一度もcloseされておらず、コメントも0**。
// フォロワーを実際に増やすのは投稿そのものではなく、キットの「2. リーチ（検索して
// 会話に入る）」の部分（docs/x-growth-playbook.md）なのに、そこが一度も回っていない。
//
// 下書きが ``` のコードブロックでしか置かれておらず、実行するには
// 「長押しで選択 → コピー → Xアプリに切り替え → 貼り付け → 投稿」という手数が要る。
// スマホでこれを毎日やるのは続かない。そこで**タップ1回でXの投稿画面/検索結果が
// 本文入りで開くリンク**を下書きの隣に置く。コードブロックは残す（PCでの
// コピペ運用と、リンクが将来Xの仕様変更で壊れたときの保険）。
//
// 【自動化ではない】これはあくまで「Xを開くところまで」を短くするだけで、
// 投稿ボタンを押すのは人間。自動投稿・自動フォローはToS違反なのでやらない、という
// 既存方針（docs/x-growth-playbook.md）は変えていない。

// Xの投稿画面を本文入りで開くURL。
// x.com/intent/post は公式のWeb Intent（旧 twitter.com/intent/tweet）。スマホでは
// Xアプリの投稿画面が、PCではブラウザの投稿ダイアログが本文入りで開く。
// 本文はそのままURLに載せるので、# や改行を含めて encodeURIComponent で必ず包む
// （包まないと「#今期アニメ」の # 以降がフラグメント扱いで丸ごと落ちる）。
function xPostUrl(text) {
  return `https://x.com/intent/post?text=${encodeURIComponent(text)}`;
}

// Xの検索結果を開くURL。
// f=live は「話題」ではなく「最新」タブ。困りごと（「どこで見れる？」）は鮮度が命で、
// 何日も前の投稿にリプライしても会話にならないため、既定を最新順にしておく。
function xSearchUrl(query) {
  return `https://x.com/search?q=${encodeURIComponent(query)}&f=live`;
}

module.exports = { xPostUrl, xSearchUrl };
